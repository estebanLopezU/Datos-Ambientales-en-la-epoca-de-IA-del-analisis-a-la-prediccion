def _clave_desde_archivo():
    """
    SECRET_KEY: variable de entorno (Vercel) > archivo local > aleatoria.

    En Vercel no existe el archivo .secret_key y la clave viene de
    `vercel env add SECRET_KEY`; en local se sigue usando el archivo para
    no dejar una clave secreta dentro del codigo compartido.
    """
    env = os.environ.get("SECRET_KEY", "").strip()
    if env:
        return env
    ruta = BASE_DIR / ".secret_key"
    if ruta.exists():
        contenido = ruta.read_text(encoding="utf-8").strip()
        if contenido:
            return contenido
    from django.core.management.utils import get_random_secret_key
    return get_random_secret_key()


# SECURITY WARNING: keep the secret key used in production secret!
SECRET_KEY = _clave_desde_archivo()


