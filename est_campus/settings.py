# Database
# https://docs.djangoproject.com/en/6.1/ref/settings/#databases

# En Vercel se usa la copia ligera db_vercel.sqlite3 (ultimos dias, creada
# con scripts/crear_db_vercel.py): la base completa (~1.1 GB) no cabe en el
# bundle de 500 MB. En local se sigue usando db.sqlite3 tal cual.
#
# MEJORA: la ruta se puede mover fuera de OneDrive (OneDrive + SQLite se
# pelean: sincroniza el archivo mientras Django escribe y puede corromperlo
# o dejarlo en "database is locked"). Para moverla:
#   1. Cierra el servidor.
#   2. Mueve db.sqlite3 a C:\Datos\est_campus\db.sqlite3 (ejemplo).
#   3. Define $env:ESTCAMPUS_DB_PATH = "C:\Datos\est_campus\db.sqlite3".
# Sin la variable, se usa el db.sqlite3 junto al proyecto (como hasta ahora).
_DB_NOMBRE = os.environ.get('ESTCAMPUS_DB_PATH', '').strip() or str(
    (BASE_DIR / 'db_vercel.sqlite3') if EN_VERCEL
    else (BASE_DIR / 'db.sqlite3'))
DATABASES = {
    'default': {
        'ENGINE': 'django.db.backends.sqlite3',
        'NAME': _DB_NOMBRE,
        'OPTIONS': {
            # Espera hasta 10 s si otra escritura bloquea el archivo, en lugar de
            # fallar con "database is locked" mientras el endpoint recibe datos.
            'timeout': 10,
        },
    }
}


